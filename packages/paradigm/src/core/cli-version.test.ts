/**
 * Identity strings shipped to every project: the AGENTS.md header links the
 * real repository and carries the installed CLI version, and the shift prompt
 * names no stale version.
 */
import { describe, it, expect, afterEach } from 'vitest';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { fileURLToPath } from 'node:url';
import {
  findParadigmVersionFrom,
  getParadigmCliVersion,
  PARADIGM_PACKAGE_NAME,
  PARADIGM_REPO_URL,
} from './cli-version.js';
import { agentsAdapter } from './ide-adapters/agents.js';
import { createMockParadigmFiles } from '../test-utils.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(fs.readFileSync(path.join(here, '..', '..', 'package.json'), 'utf8')) as {
  name: string;
  version: string;
};

let tmp: string | undefined;
afterEach(() => {
  if (tmp) fs.rmSync(tmp, { recursive: true, force: true });
  tmp = undefined;
});

describe('getParadigmCliVersion', () => {
  it('returns this package.json version', () => {
    expect(pkg.name).toBe(PARADIGM_PACKAGE_NAME);
    expect(getParadigmCliVersion()).toBe(pkg.version);
  });

  it('skips a package.json with another name and returns null when none matches', () => {
    tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'paradigm-cli-version-'));
    const inner = path.join(tmp, 'a', 'b');
    fs.mkdirSync(inner, { recursive: true });
    fs.writeFileSync(path.join(inner, 'package.json'), JSON.stringify({ name: 'other', version: '9.9.9' }), 'utf8');
    fs.writeFileSync(
      path.join(tmp, 'a', 'package.json'),
      JSON.stringify({ name: PARADIGM_PACKAGE_NAME, version: '1.2.3' }),
      'utf8',
    );
    expect(findParadigmVersionFrom(inner)).toBe('1.2.3');
    fs.rmSync(path.join(tmp, 'a', 'package.json'));
    // No matching package.json between `inner` and the filesystem root.
    expect(findParadigmVersionFrom(inner)).toBeNull();
  });
});

describe('AGENTS.md header', () => {
  const header = agentsAdapter
    .generate(createMockParadigmFiles())
    .split('\n')
    .find((l) => l.startsWith('> Generated by'));

  it('links the real repository', () => {
    expect(PARADIGM_REPO_URL).toBe('https://github.com/ascend42/a-paradigm');
    expect(header).toContain(`[Paradigm](${PARADIGM_REPO_URL})`);
    expect(header).not.toContain('anthropics');
  });

  it('carries the package version, not a hard-coded v2.0', () => {
    expect(header).toContain(` v${pkg.version} |`);
    expect(header).not.toContain('v2.0');
  });
});

describe('shift prompt copy', () => {
  it('names no stale Paradigm version', () => {
    const src = fs.readFileSync(path.join(here, '..', 'commands', 'shift.ts'), 'utf8');
    const printed = src.split('\n').filter((l) => l.includes('console.log('));
    for (const line of printed) expect(line).not.toMatch(/paradigm \d+\.\d+\.\d+/i);
  });
});
