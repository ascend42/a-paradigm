/**
 * Identity strings shipped to every project. The AGENTS.md header links the
 * real repository and carries NO version (a product version would rewrite the
 * line in every user's repo on each upgrade). The CLAUDE.md trailer labels the
 * symbol-schema version as a schema version, not as "Paradigm v2.0".
 */
import { describe, it, expect } from 'vitest';
import { agentsAdapter } from './agents.js';
import { claudeAdapter, ClaudeAdapter } from './claude.js';
import { PARADIGM_REPO_URL } from './types.js';
import { createMockParadigmFiles } from '../../test-utils.js';

describe('AGENTS.md header', () => {
  const header = agentsAdapter
    .generate(createMockParadigmFiles())
    .split('\n')
    .find((l) => l.startsWith('> Generated by'));

  it('links the real repository', () => {
    expect(PARADIGM_REPO_URL).toBe('https://github.com/ascend42/a-paradigm');
    expect(header).toBe(`> Generated by [Paradigm](${PARADIGM_REPO_URL}) | Universal AI agent instruction file`);
    expect(header).not.toContain('anthropics');
  });

  it('carries no version number', () => {
    expect(header).not.toMatch(/\bv?\d+\.\d+/);
  });
});

describe('CLAUDE.md trailer', () => {
  const trailerOf = (md: string): string => md.slice(md.indexOf(ClaudeAdapter.TRAILER_MARKER));

  it('labels the schema version as "symbol schema v2", never "Paradigm v2.0"', () => {
    const md = claudeAdapter.generate(createMockParadigmFiles());
    expect(trailerOf(md)).toContain('> **Paradigm** (symbol schema v2) | For Claude Code');
    expect(md).not.toContain('Paradigm v2.0');
  });

  it('a supplied schema version is still labelled as the schema', () => {
    const md = claudeAdapter.generate({ ...createMockParadigmFiles(), meta: { paradigmVersion: 'v3' } });
    expect(trailerOf(md)).toContain('> **Paradigm** (symbol schema v3) |');
  });
});
