#!/usr/bin/env node
// #gnomon-wrapper cross-language vectors (spec §4.9 serverSig, §11.2 rule 1a tree hash).
// Regenerates test/fixtures/vectors-v1.json from the TypeScript definitions the
// kernel and the GUI use (gnomon-contracts authServerPreimage; the kernel's
// gnomon-bundle-tree:v1, packages/gnomon/src/kernel/web/bundle.ts treeHashOf)
// so the Rust verifier is checked against the same bytes the kernel signs.
// Deterministic (fixed seed): rerunning yields an identical file.
//   npm run build:gnomon && node packages/gnomon-wrapper/scripts/gen-fixtures.mjs
import { createHash, createPrivateKey, createPublicKey, sign } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { authServerPreimage } from '../../gnomon-contracts/dist/index.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const seed = createHash('sha256').update('gnomon-wrapper fixture seed v1').digest();
const priv = createPrivateKey({ key: Buffer.concat([Buffer.from('302e020100300506032b657004220420', 'hex'), seed]), format: 'der', type: 'pkcs8' });
const pub = createPublicKey(priv);
const spki = pub.export({ type: 'spki', format: 'der' });
const pem = pub.export({ type: 'spki', format: 'pem' }).toString().replace(/\n+$/, '');
const keyId = `gkey:v1:${createHash('sha256').update(pem, 'utf8').digest('hex')}`;

const port = 49152;
const endpointPath = `ws://127.0.0.1:${port}/rpc`;
const nonce = 'c2VydmVyLW5vbmNlLWZpeGVkLWZvci10aGUtdmVjdG9y';
const clientNonce = 'Y2xpZW50LW5vbmNlLWZpeGVkLWZvci10aGUtdmVjdG9yLTMyYg';
const cases = [
  { clientApi: 'gnomon-rpc:v1', features: [] },
  { clientApi: 'gnomon-rpc:v1', features: ['log.follow', 'cards.v2'] },
];
const hello = cases.map((n) => {
  const preimage = authServerPreimage(nonce, clientNonce, endpointPath, n);
  return { nonce, clientNonce, serverKeyId: keyId, clientApi: n.clientApi, features: n.features, endpointPath, preimage, serverSig: sign(null, Buffer.from(preimage, 'utf8'), priv).toString('base64') };
});

// gnomon-bundle-tree:v1, verbatim from bundle.ts treeHashOf
function treeHash(files) {
  const names = [...files.keys()].sort((a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b)));
  const h = createHash('sha256').update('gnomon-bundle-tree:v1\n');
  for (const n of names) h.update(`${n}\0${createHash('sha256').update(files.get(n)).digest('hex')}\n`);
  return `sha256:${h.digest('hex')}`;
}
const files = new Map([
  ['index.html', Buffer.from('<!doctype html>\n<title>t</title>\n')],
  ['app.js', Buffer.from("'use strict';\n")],
  ['assets/Zed.woff2', Buffer.from([0, 1, 2, 255])],
  ['B.css', Buffer.from('')],
]);
const bundle = { files: [...files].map(([name, b]) => ({ name, b64: b.toString('base64') })), hash: treeHash(files) };

const out = {
  note: 'GENERATED by scripts/gen-fixtures.mjs from gnomon-contracts authServerPreimage and the kernel tree hash; do not edit',
  kernelPublicKey: spki.toString('base64url'),
  keyId,
  hello,
  bundle,
};
mkdirSync(path.join(ROOT, 'test', 'fixtures'), { recursive: true });
writeFileSync(path.join(ROOT, 'test', 'fixtures', 'vectors-v1.json'), `${JSON.stringify(out, null, 2)}\n`);
process.stdout.write(`wrote test/fixtures/vectors-v1.json (${hello.length} hello vectors, bundle ${bundle.hash.slice(0, 19)}…)\n`);
