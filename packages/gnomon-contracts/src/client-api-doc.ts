/**
 * The generated client-API document (spec §12.8: "`docs/specs/gnomon-client-api.md`
 * is generated from the schemas (never hand-maintained, G-HON-04's
 * fixed-point rule)"; M1.12 slice 3).
 *
 * `renderClientApiDoc()` is a pure function of this package's published
 * values — the descriptor inputs of clientApiId, the refusal registry, the
 * schema files, the kit, the display rules and the conformance catalog — so
 * the committed file is its byte-identical fixed point
 * (test/client-api-doc.test.ts; regenerate with `npm run client-api-doc`).
 * NOT an input to clientApiId: it reads the descriptor, never adds to it.
 */

import { CLIENT_API_ID, KIT_ID, KIT_V1, KIT_V1_BLOCKS } from './client-api.js';
import { CONFORMANCE_CHECKS, CONFORMANCE_SUITE, CONFORMANCE_VERSION } from './conformance.js';
import { BIDI_GLYPHS, HIDDEN_STRIP_RANGES } from './display.js';
import { EVENT_KIND_NAMES, OPEN_USERLAND_NAMESPACES } from './event.js';
import { JSON_RPC_CODES, REFUSAL_REASONS } from './refusal.js';
import { ADDITIVE_ENUMS, CLIENT_RELAYS, GNOMON_RPC_V1, HUMAN_DEVICE_VERBS, LOG_READ_CURSOR_KEYS, RESERVED_HELLO_FEATURES, VERBS } from './rpc.js';
import { DECISION_SIG_V2_MARKER } from './card.js';
import { CONTRACT_SCHEMAS } from './schemas.js';

export const CLIENT_API_DOC_PATH = 'docs/specs/gnomon-client-api.md' as const;

/** Markdown table cell: pipes escaped, newlines flattened. */
const cell = (v: unknown): string => String(v).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const hexCp = (n: number): string => `U+${n.toString(16).toUpperCase().padStart(4, '0')}`;

export function renderClientApiDoc(): string {
  const L: string[] = [];
  L.push('# Gnomon client API (`gnomon-rpc:v1`) — generated');
  L.push('');
  L.push('<!-- GENERATED by @a-company/gnomon-contracts renderClientApiDoc() (src/client-api-doc.ts). Do not edit:');
  L.push('     run `npm run client-api-doc --workspace=@a-company/gnomon-contracts`. The committed file is a fixed point (G-HON-04). -->');
  L.push('');
  L.push('Everything a community client needs is published by `@a-company/gnomon-contracts` (spec §12.8). This page is rendered from the package; where it and the spec differ, the package is the published surface and the spec is the design.');
  L.push('');
  L.push('## Identity');
  L.push('');
  L.push(`- clientApi: \`${GNOMON_RPC_V1}\``);
  L.push(`- clientApiId: \`${CLIENT_API_ID}\` (pinned in \`schemas/client-api.ids.json\`)`);
  L.push(`- kitId: \`${KIT_ID}\` (\`${KIT_V1}\`)`);
  L.push('- clientApiId = sha256(canonicalJson(descriptor) + "\\n" + kitId); modAbiId is not an input.');
  L.push('');
  L.push(`## Verbs (${VERBS.length}), human-device verbs (${HUMAN_DEVICE_VERBS.length}) and client relays (${CLIENT_RELAYS.length})`);
  L.push('');
  const classes = Object.keys(VERBS[0]!.access);
  L.push(`| # | verb | params | result | refusals | human only | ${classes.join(' | ')} |`);
  L.push(`|---|---|---|---|---|---|${classes.map(() => '---').join('|')}|`);
  for (const v of [...VERBS, ...HUMAN_DEVICE_VERBS]) {
    const acc = v.access as Readonly<Record<string, string | boolean>>;
    L.push(`| ${v.n} | \`${v.verb}\` | ${cell(v.params.join(', ') || '—')} | ${cell(v.result)} | ${cell(v.refusals.join(', '))} | ${v.humanOnly ? 'yes' : 'no'} | ${classes.map((c) => cell(acc[c] === false ? 'no' : acc[c])).join(' | ')} |`);
  }
  L.push('');
  L.push('| relay | params | forwards as |');
  L.push('|---|---|---|');
  for (const r of CLIENT_RELAYS) L.push(`| \`${r.relay}\` | ${cell(r.params.join(', '))} | \`${r.forwardsAs}\` |`);
  L.push('');
  L.push('Verbs 13–14 are human-device verbs (P8-D98): only a human principal on a device connection whose hello verified the kernel key may call them; they are not among law 3\'s twelve kernel verbs.');
  L.push('');
  L.push('## Reserved (P8-D98)');
  L.push('');
  L.push(`- hello features: ${RESERVED_HELLO_FEATURES.map((f) => `\`${f}\``).join(', ')} — the kernel advertises none until it builds them; a missing feature refuses the dependent operation, never degrades it.`);
  L.push(`- \`log.read\` cursor: \`{${LOG_READ_CURSOR_KEYS.join(', ')}}\`; a cursor from another log is \`BAD_REQUEST{reason:'cursor-epoch'}\`.`);
  L.push(`- decisionSig v2: first line \`${DECISION_SIG_V2_MARKER}\`, used for \`answer\` decisions, carrying the answer digest.`);
  L.push('');
  L.push('## Refusals (`refusal:v1`)');
  L.push('');
  L.push('| code | JSON-RPC code |');
  L.push('|---|---|');
  for (const [code, n] of Object.entries(JSON_RPC_CODES)) L.push(`| \`${code}\` | ${n} |`);
  L.push('');
  L.push(`Named reasons (additive; render an unknown one opaquely): ${[...REFUSAL_REASONS].map((r) => `\`${r}\``).join(', ')}.`);
  L.push('');
  L.push('## Compatible-additive enums');
  L.push('');
  L.push('A client renders an unknown value of these opaquely and never drops the item; every other closed set changing is a v2.');
  L.push('');
  for (const [name, values] of Object.entries(ADDITIVE_ENUMS)) L.push(`- \`${name}\`: ${(values as readonly string[]).map((x) => `\`${x}\``).join(', ')}`);
  L.push('');
  L.push(`## Event kinds (${EVENT_KIND_NAMES.length} registered)`);
  L.push('');
  L.push(`Open namespaces (any well-formed kind is valid): ${OPEN_USERLAND_NAMESPACES.map((n) => `\`${n}\``).join(', ')}. A \`modns.*\` kind or a kind newer than the package is listed as an opaque \`{kind, principal, at}\` row.`);
  L.push('');
  L.push(EVENT_KIND_NAMES.map((k) => `\`${k}\``).join(', '));
  L.push('');
  L.push('## Schemas');
  L.push('');
  L.push('| file | title | $id |');
  L.push('|---|---|---|');
  for (const [file, s] of Object.entries(CONTRACT_SCHEMAS)) {
    const o = s as { title?: unknown; $id?: unknown };
    L.push(`| \`schemas/${file}\` | ${cell(o.title ?? '')} | ${cell(o.$id ?? '')} |`);
  }
  L.push('');
  L.push('## Kit and display rules');
  L.push('');
  L.push(`Kit blocks: ${KIT_V1_BLOCKS.map((b) => `\`kit.${b}\``).join(', ')}. A block carries no actions; decision controls exist only on kernel-signed \`card:v1.actions[]\`.`);
  L.push('');
  L.push('Every string passes the §4.5 sanitizer (`sanitizeDisplayText`) before it is rendered; `conformance/display.v1.json` is normative and a conformant client reproduces it byte for byte.');
  L.push('');
  L.push(`- stripped (flag \`hidden-chars\`): ${HIDDEN_STRIP_RANGES.map(([a, b]) => (a === b ? hexCp(a) : `${hexCp(a)}–${hexCp(b)}`)).join(', ')}`);
  L.push(`- shown as glyphs (flag \`bidi\`): ${Object.entries(BIDI_GLYPHS).map(([cp, g]) => `${hexCp(Number(cp))} → ${g}`).join(', ')}`);
  L.push('- every number is shown as `{n, of}` (`renderDenominator`); a bare count is refused.');
  L.push('');
  L.push(`## Conformance (\`${CONFORMANCE_SUITE}\` v${CONFORMANCE_VERSION})`);
  L.push('');
  L.push('`status` labels what a client declares in `hello{client.conformance}` as `declared`, never `passed`.');
  L.push('');
  L.push('| check | a conformant client | spec | runner |');
  L.push('|---|---|---|---|');
  for (const c of CONFORMANCE_CHECKS) L.push(`| \`${c.id}\` | ${cell(c.must)} | ${cell(c.spec)} | ${c.status === 'run' ? 'run' : 'catalogued, reported todo'} |`);
  L.push('');
  return `${L.join('\n')}`;
}
