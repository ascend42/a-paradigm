#!/usr/bin/env node
// #gui bundle build (spec §11.1, §11.2 rule 1a). Bundles src/main.ts (with @a-company/gnomon-contracts inlined, no
// runtime fetch of anything) into dist/bundle/{index.html, boot.js, styles.css, app.js}, adds the lazy #gui-board
// chunk (dist/bundle/board/*, scripts/board-build.mjs: its own ES module, never part of app.js), hashes the WHOLE
// tree with the kernel's `gnomon-bundle-tree:v1` definition (packages/gnomon/src/kernel/web/bundle.ts treeHashOf) and:
//   --embed  writes packages/gnomon/src/kernel/web/gui-bundle.ts (the files as opaque base64 + the pin literal)
//   --check  fails when that generated file is not byte-identical to a fresh build (the pin cannot drift), and says
//            which board file is unpinned, or that the board chunk is over its budget or carries a sourcemap
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BOARD_BUDGET_BYTES, BOARD_DIR, boardProblems, buildBoard, embeddedFiles, unpinnedBoardFiles } from './board-build.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'dist', 'bundle');
const EMBED = path.resolve(ROOT, '..', 'gnomon', 'src', 'kernel', 'web', 'gui-bundle.ts');
// Text files get LF on every OS (B3); everything else (the bundled woff2 fonts) is carried as raw bytes, never
// decoded: a utf8 round-trip or a CRLF strip would corrupt a binary (S1, critique §2 S1.1).
export const TEXT_EXT = new Set(['.html', '.css', '.js', '.mjs', '.json', '.map', '.svg', '.txt']);

/** Every regular file under static/, relative POSIX path → bytes (text LF-normalized, binaries raw). */
export function staticFiles(dir = path.join(ROOT, 'static')) {
  const out = new Map();
  const visit = (abs, rel) => {
    for (const name of readdirSync(abs).sort()) {
      if (name.startsWith('.')) continue; // dotfiles (.DS_Store, editor droppings) never enter the pinned bundle
      const full = path.join(abs, name);
      const r = rel ? `${rel}/${name}` : name;
      const st = lstatSync(full);
      if (st.isSymbolicLink()) continue; // never follow a link out of static/ (the kernel refuses symlinks too)
      if (st.isDirectory()) visit(full, r);
      else if (!st.isFile()) continue;
      else if (TEXT_EXT.has(path.extname(name).toLowerCase())) out.set(r, Buffer.from(readFileSync(full, 'utf8').replace(/\r\n/g, '\n'), 'utf8'));
      else out.set(r, readFileSync(full));
    }
  };
  visit(dir, '');
  return out;
}

export async function buildFiles() {
  const r = await build({
    entryPoints: [path.join(ROOT, 'src', 'main.ts')],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify: false,
    legalComments: 'none',
    charset: 'utf8',
    // Aegis L1: preview-only paths (devArmOfferOnce) are dead code in the served bundle
    define: { __GNOMON_PREVIEW__: 'false' },
    minifySyntax: true, // drops the define's dead branches (whitespace and names stay readable)
    write: false,
    logLevel: 'silent',
  });
  const files = new Map();
  files.set('app.js', Buffer.from(`'use strict';\n${r.outputFiles[0].text}`, 'utf8'));
  for (const [n, b] of staticFiles()) files.set(n, b);
  // the board chunk joins the SAME tree: one hash pins app.js, static/ and board/ (Aegis S1 risk d)
  for (const [n, b] of (await buildBoard()).files) {
    if (files.has(n)) throw new Error(`board file ${n} collides with a GUI file`);
    files.set(n, b);
  }
  const problems = boardProblems(files);
  if (problems.length) throw new Error(`gui bundle: ${problems.join('; ')}`);
  return files;
}

/** Raw bytes of the board chunk in a file map. */
export const boardBytes = (files) => [...files].reduce((a, [n, b]) => a + (n.startsWith(`${BOARD_DIR}/`) ? b.length : 0), 0);

export function treeHash(files) {
  const names = [...files.keys()].sort((a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b)));
  const h = createHash('sha256').update('gnomon-bundle-tree:v1\n');
  for (const n of names) h.update(`${n}\0${createHash('sha256').update(files.get(n)).digest('hex')}\n`);
  return `sha256:${h.digest('hex')}`;
}

export function embedSource(files, hash) {
  const entries = [...files.keys()].sort().map((n) => `  ${JSON.stringify(n)}:\n    ${JSON.stringify(files.get(n).toString('base64'))},`);
  return `/**
 * @symbol #web-endpoint
 *
 * GENERATED by packages/gnomon-gui/scripts/build.mjs --embed — do not edit.
 * The pinned #gui bundle (M1.10 slice 1) as OPAQUE base64 bytes: the kernel
 * never evaluates, imports or inspects GUI code, it materializes these bytes
 * and compares a digest (spec §11.2 rule 1a, \`G-WEB-08\`). GUI_BUNDLE_HASH is
 * the gnomon-bundle-tree:v1 hash of exactly these files (test/web-units.test.ts
 * and packages/gnomon-gui \`--check\` prove both directions).
 */
export const GUI_BUNDLE_FILES_B64: Readonly<Record<string, string>> = Object.freeze({
${entries.join('\n')}
});

export const GUI_BUNDLE_HASH = ${JSON.stringify(hash)};
`;
}

const mode = process.argv[2] ?? '';
const files = await buildFiles();
const hash = treeHash(files);
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const [n, b] of files) {
  mkdirSync(path.dirname(path.join(OUT, n)), { recursive: true });
  writeFileSync(path.join(OUT, n), b);
}
const src = embedSource(files, hash);
if (mode === '--embed') {
  writeFileSync(EMBED, src);
  process.stdout.write(`embedded ${files.size} files · ${hash}\n`);
} else if (mode === '--check') {
  let cur = '';
  try {
    cur = readFileSync(EMBED, 'utf8').replace(/\r\n/g, '\n');
  } catch {}
  // name the board files first: an unpinned board file would be served outside the hash the kernel checks
  const unpinned = unpinnedBoardFiles(files, embeddedFiles(cur));
  for (const u of unpinned) process.stderr.write(`✕ board: ${u}\n`);
  if (cur !== src || unpinned.length) {
    process.stderr.write(`✕ gui-bundle.ts is stale: run \`npm run embed --workspace=@a-company/gnomon-gui\` (fresh ${hash})\n`);
    process.exit(1);
  }
  process.stdout.write(`✓ gui-bundle.ts matches the fresh build · ${hash}\n`);
  process.stdout.write(`✓ board chunk pinned in the tree · ${[...files.keys()].filter((n) => n.startsWith(`${BOARD_DIR}/`)).length} files · ${boardBytes(files)} of ${BOARD_BUDGET_BYTES} bytes · no sourcemap\n`);
} else process.stdout.write(`built ${files.size} files → dist/bundle · ${hash}\n`);
