#!/usr/bin/env node
// Regenerates safari.html from ed25519-test.js (the BEGIN/END block is inlined
// verbatim so the hand-run page tests exactly what the engines test).
//   node packages/gnomon/probes/p09-ed25519-matrix/make-safari-html.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));

export function testBody() {
  const src = readFileSync(path.join(dir, 'ed25519-test.js'), 'utf8');
  const a = src.indexOf('// BEGIN p09Ed25519Test');
  const end = '// END p09Ed25519Test';
  const b = src.indexOf(end);
  return src.slice(a, b + end.length);
}

export function renderSafariHtml() {
  return `<!doctype html>
<!-- p09-ed25519-matrix, Safari by hand (spec §19.1 P09, §11.1). Self-contained:
     open this file in real Safari (File > Open File, or drag it onto a Safari
     window), then copy the line it prints and paste it back. Line format:
     packages/gnomon/probes/README.md, section P09. GENERATED by
     make-safari-html.mjs from ed25519-test.js; the probe's sync check fails if
     they drift. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Gnomon P09 — Ed25519 in Safari</title>
<style>
  body { font: 15px/1.5 ui-monospace, Menlo, monospace; margin: 40px; background: #f8f5ee; color: #16150f; }
  #line { font-size: 20px; padding: 16px; border: 1px solid #16150f; background: #fff; user-select: all; }
  .meta { color: #5a5850; font-size: 12px; margin-top: 12px; overflow-wrap: anywhere; }
  button { font: inherit; margin-top: 12px; padding: 4px 12px; }
</style>
</head>
<body>
<h1>Gnomon P09: Ed25519 in this browser</h1>
<p>Copy the line below and paste it back to Claude.</p>
<div id="line">running…</div>
<button id="copy" type="button">copy line</button>
<div class="meta" id="meta"></div>
<script>
${testBody()}
(async function () {
  var r;
  try { r = await globalThis.p09Ed25519Test(); } catch (e) { r = { line: 'ed25519 ✕ unsupported (' + e + ') · FAIL' }; }
  var v = (navigator.userAgent.match(/Version\\/([0-9.]+)/) || [])[1] || '?';
  var full = r.line + ' · safari ' + v + ' · ' + location.protocol.replace(':', '');
  document.getElementById('line').textContent = full;
  document.getElementById('meta').textContent = navigator.userAgent + ' · secureContext=' + r.secureContext + (r.error ? ' · ' + r.error : '');
  document.getElementById('copy').onclick = function () { if (navigator.clipboard) navigator.clipboard.writeText(full); };
})();
</script>
</body>
</html>
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(dir, 'safari.html'), renderSafariHtml());
  process.stdout.write('wrote safari.html\n');
}
