#!/usr/bin/env node
// build:dimension-mod — generates packages/gnomon-mods/dimension/dim-shape.mjs (#dimension-mod, spec §12.7).
//
// The dimension mod runs from a pinned snapshot and imports nothing outside its folder, so the `dim-shape:v1`
// fold and validator (packages/gnomon-contracts/src/dim.ts and its three imports) are bundled INTO the tree.
// The output is committed; test/dimension-mod.test.ts rebuilds it and compares bytes, so the mod can never
// run a fold that differs from the published contract. Deterministic on every OS: the entry is a
// forward-slash path relative to the contracts package, path comments are stripped, newlines are LF.
// After a change to dim.ts: run this, then repin the mod (FIRST_PARTY_PACKAGE_HASHES in install.ts).
import * as fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const contracts = path.resolve(here, '..', '..', 'gnomon-contracts');
export const DIM_SHAPE_OUT = path.resolve(here, '..', '..', 'gnomon-mods', 'dimension', 'dim-shape.mjs');
const HEADER = '// GENERATED by packages/gnomon/scripts/build-dimension-mod.mjs from packages/gnomon-contracts/src/dim.ts.\n// Do not edit: a test rebuilds this file and compares bytes.\n';

/** The bundle text (LF, no path comments). */
export async function buildDimShape() {
  const out = await build({
    absWorkingDir: contracts,
    entryPoints: ['src/dim.ts'],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    minify: false,
    legalComments: 'none',
    charset: 'utf8',
    sourcemap: false,
    write: false,
    logLevel: 'silent',
  });
  const text = out.outputFiles[0].text.replace(/\r\n/g, '\n');
  // esbuild marks each bundled module with a `// <path>` line: drop those (a path is not part of the contract)
  const body = text
    .split('\n')
    .filter((line) => !/^\/\/ [\w./\\-]+\.ts$/.test(line))
    .join('\n');
  return `${HEADER}${body.endsWith('\n') ? body : `${body}\n`}`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await buildDimShape();
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(DIM_SHAPE_OUT) ? fs.readFileSync(DIM_SHAPE_OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== text) {
      process.stderr.write('dim-shape.mjs is stale: run node scripts/build-dimension-mod.mjs\n');
      process.exit(1);
    }
    process.stdout.write('dim-shape.mjs is current\n');
  } else {
    fs.mkdirSync(path.dirname(DIM_SHAPE_OUT), { recursive: true });
    fs.writeFileSync(DIM_SHAPE_OUT, text);
    process.stdout.write(`wrote ${path.relative(path.resolve(here, '..', '..'), DIM_SHAPE_OUT).split(path.sep).join('/')} (${Buffer.byteLength(text)} bytes)\n`);
  }
}
